pub fn plane(half: f32, slope: f32) -> CollisionWorld {
    let (s, c) = slope.sin_cos();
    let p = |x: f32, z: f32| Vec3::new(x, -z * s, z * c);
    let v = [p(-half, -half), p(-half, half), p(half, half), p(half, -half)];
    let mut w = CollisionWorld::default();
    w.push_cluster(&v, None, None, &[[0, 1, 2], [0, 2, 3]], 0, 0);
    w.finish();
    w
}

pub fn add_quad(w: &mut CollisionWorld, corners: [Vec3; 4], class: u8) {
    w.push_cluster(&corners, None, None, &[[0, 1, 2], [0, 2, 3]], 0, class);
}

pub fn add_floor(w: &mut CollisionWorld, x: [f32; 2], z: [f32; 2], y: f32, class: u8) {
    let p = |x: f32, z: f32| Vec3::new(x, y, z);
    add_quad(w, [p(x[0], z[0]), p(x[0], z[1]), p(x[1], z[1]), p(x[1], z[0])], class);
}

